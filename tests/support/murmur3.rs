use zenhash::{Murmur3_32, Murmur3X64_128, murmur3_32, murmur3_x64_128};

// Produced by the independent SMHasher C++ implementation, never by the Rust code.
const GOLDEN: &str = include_str!("../reference/murmur3.txt");
const GOLDEN_128: &str = include_str!("../reference/murmur3-128.txt");

#[test]
fn canonical_smhasher_verification_codes() {
    // Schedule: SMHasher KeysetTest.cpp::VerificationTest. Expected values:
    // https://github.com/aappleby/smhasher/blob/07bb4de10a63e8cc2e1724865454eba635742383/src/main.cpp
    fn verification(hash: impl Fn(&[u8], u32) -> Vec<u8>) -> u32 {
        let key: Vec<u8> = (0..256).map(|i| i as u8).collect();
        let mut hashes = Vec::new();
        for len in 0..256 {
            hashes.extend_from_slice(&hash(&key[..len], 256 - len as u32));
        }
        u32::from_le_bytes(hash(&hashes, 0)[..4].try_into().unwrap())
    }
    assert_eq!(
        verification(|data, seed| murmur3_32(data, seed).to_le_bytes().to_vec()),
        0xb0f5_7ee3
    );
    assert_eq!(
        verification(|data, seed| murmur3_x64_128(data, seed).to_le_bytes().to_vec()),
        0x6384_ba69
    );
}

#[test]
fn x64_128_c_goldens_all_tail_boundaries_and_streams() {
    for line in GOLDEN_128.lines().filter(|s| !s.starts_with('#')) {
        let parts: Vec<_> = line.split_whitespace().collect();
        assert_eq!(parts.len(), 4);
        let seed = u32::from_str_radix(parts[0], 16).unwrap();
        let len: usize = parts[1].parse().unwrap();
        let expected = u128::from_str_radix(parts[2], 16).unwrap();
        let x86_variant = u128::from_str_radix(parts[3], 16).unwrap();
        let data: Vec<u8> = (0..len).map(|i| (i * 37 + 11) as u8).collect();
        assert_eq!(
            murmur3_x64_128(&data, seed),
            expected,
            "len={len} seed={seed}"
        );
        if seed == 0 && len == 1 {
            // This fixture distinguishes algorithms even when running on x86.
            assert_ne!(expected, x86_variant);
        }
        for split in (0..=len.min(68)).chain(len.saturating_sub(68)..=len) {
            let mut state = Murmur3X64_128::with_seed(seed);
            state.update(&data[..split]);
            let snapshot = state.digest();
            let mut cloned = state.clone();
            assert_eq!(snapshot, state.digest());
            state.update(&[]);
            state.update(&data[split..]);
            cloned.update(&data[split..]);
            assert_eq!(
                state.digest(),
                expected,
                "len={len} split={split} seed={seed}"
            );
            assert_eq!(cloned.digest(), expected);
        }
        let mut state = Murmur3X64_128::with_seed(seed);
        for byte in &data {
            state.update(core::slice::from_ref(byte));
        }
        assert_eq!(state.digest(), expected);
        for offset in 1..16 {
            let mut unaligned = vec![0; offset];
            unaligned.extend_from_slice(&data);
            assert_eq!(murmur3_x64_128(&unaligned[offset..], seed), expected);
        }
    }
}

#[test]
fn x64_128_const_and_canonical_word_order() {
    const DATA: [u8; 17] = {
        let mut data = [0; 17];
        let mut i = 0;
        while i < data.len() {
            data[i] = (i * 37 + 11) as u8;
            i += 1;
        }
        data
    };
    const VALUE: u128 = {
        let mut state = Murmur3X64_128::with_seed(42);
        state.update(DATA.split_at(2).0);
        state.update(DATA.split_at(2).1);
        state.digest()
    };
    // The independently generated fixture supplies the numerical value and
    // both reference output words; expected bytes are not generated by Rust.
    let line = GOLDEN_128
        .lines()
        .find(|s| s.starts_with("0000002a 17 "))
        .unwrap();
    let hex = line.split_whitespace().nth(2).unwrap();
    let expected = u128::from_str_radix(hex, 16).unwrap();
    const ONE_SHOT: u128 = murmur3_x64_128(&DATA, 42);
    assert_eq!(VALUE, expected);
    assert_eq!(ONE_SHOT, expected);
    let low = u64::from_str_radix(&hex[16..], 16).unwrap().to_le_bytes();
    let high = u64::from_str_radix(&hex[..16], 16).unwrap().to_le_bytes();
    assert_eq!(&murmur3_x64_128(&DATA, 42).to_le_bytes()[..8], &low);
    assert_eq!(&murmur3_x64_128(&DATA, 42).to_le_bytes()[8..], &high);
}

#[test]
fn c_golden_pairs_and_every_split() {
    for line in GOLDEN.lines().filter(|s| !s.starts_with('#')) {
        let parts: Vec<_> = line.split_whitespace().collect();
        assert_eq!(parts.len(), 3);
        let seed = u32::from_str_radix(parts[0], 16).unwrap();
        let len: usize = parts[1].parse().unwrap();
        let expected = u32::from_str_radix(parts[2], 16).unwrap();
        let data: Vec<u8> = (0..len).map(|i| (i * 37 + 11) as u8).collect();
        assert_eq!(murmur3_32(&data, seed), expected, "len={len} seed={seed}");
        // All short splits, every tail position at both ends of long inputs.
        for split in (0..=len.min(68)).chain(len.saturating_sub(68)..=len) {
            let mut h = Murmur3_32::with_seed(seed);
            h.update(&data[..split]);
            let before = h.digest();
            assert_eq!(before, h.digest(), "digest must not mutate state");
            h.update(&[]);
            h.update(&data[split..]);
            assert_eq!(h.digest(), expected, "len={len} split={split} seed={seed}");
        }
        let mut h = Murmur3_32::with_seed(seed);
        for byte in &data {
            h.update(core::slice::from_ref(byte));
        }
        assert_eq!(h.digest(), expected, "byte updates len={len}");
        // Explicitly unaligned starts exercise the same byte order.
        let mut padded = vec![0u8];
        padded.extend_from_slice(&data);
        assert_eq!(murmur3_32(&padded[1..], seed), expected);
    }
}

#[test]
fn quickwit_published_pairs_and_const_evaluation() {
    const HASH: u32 = murmur3_32(b"abc", 3_242_157_231);
    assert_eq!(HASH, 476_091_040);
    for (input, expected) in [
        (&b""[..], 36_859_204),
        (b"a", 3_144_985_375),
        (b"ab", 3_262_304_301),
        (b"abc", 476_091_040),
        (b"abcd", 412_992_581),
        (b"abcde", 2_747_833_956),
        (b"abcdefghijklmnop", 2_078_305_053),
    ] {
        assert_eq!(murmur3_32(input, 3_242_157_231), expected);
    }
}
